import { test, expect, fresh, collapseTools, later, store, pickArmor } from './helpers'

test('sandbox editor: change rules, see the summary, save, and the run follows them', async ({ page }) => {
  await fresh(page)
  await page.click('text=Create lobby')
  await collapseTools(page)
  await page.click('.sidebar >> text=Directives')
  await page.locator('.proto', { hasText: 'Standard Directive' }).locator('button:has-text("Customize")').click()
  await page.fill('#sb-name', 'Test Directive')
  await page.fill('#sb-sandbox-finalClear', '15')
  await page.click('.sb-nav button:has-text("Starting setup")')
  await page.locator('.sb-field', { hasText: 'Kinetic and energy' }).locator('button:has-text("Rare")').click()
  await page.selectOption('#sb-sandbox-startAbilities', 'all')
  await page.click('.sb-nav button:has-text("Gear progression")')
  await page.locator('#sb-sandbox-bonusChance').fill('25')
  await page.click('[aria-label="Reset BONUS tier-up chance after a reward"]')
  await page.click('.sb-nav button:has-text("Rewards")')
  await page.uncheck('#sb-sandbox-secretChests')
  await expect(page.locator('#sb-rewards-chestArtifact')).toHaveCount(0)
  await page.click('.sb-nav button:has-text("Honour rules")')
  await page.check('#sb-sandbox-noRallyBanners')
  // App settings are not in the editor.
  await expect(page.locator('#sb-sandbox-readyGate, #sb-sandbox-resumeGate, #sb-sandbox-collectionsOnly, #sb-overflow')).toHaveCount(0)
  await expect(page.locator('.sb-diffs li')).toHaveCount(5)
  await page.click('button:has-text("Save Directive")')
  const card = page.locator('.proto', { hasText: 'Test Directive' })
  await expect(card).toContainText('Custom Directive')
  await expect(card).toContainText('5 changes from Standard Directive')
  await card.locator('button:has-text("Use in lobby")').click()
  await page.click('.sidebar >> text=Setup and rules')
  await expect(page.locator('.setup-guide')).toContainText('Grey, green or blue weapons')
  await expect(page.locator('.setup-guide')).toContainText('A final boss gives +15 more')
  await expect(page.locator('.setup-guide')).not.toContainText('No aspects')
  await expect(page.locator('.setup-guide')).toContainText('No Rally Banners: don’t place a Rally Banner')
  await page.click('.seat.is-you .art-pick [role=radio][title^="Tablet of Ruin"]')
  await pickArmor(page)
  await page.click('button:has-text("Begin run")')
  await expect(page.locator('.command')).toBeVisible()
  await later(page)
  const run = (await store(page)).active
  expect(run.players[0].tiers.Kinetic).toBe('Rare')
  expect(run.players[0].unlocked.length).toBeGreaterThan(30)
  await expect(page.locator('.command .progress-split')).toHaveCount(0)
  await expect(page.locator('.page-head .honour-tag')).toHaveText('No Rally Banners')
})

test('Directive JSON exports and imports', async ({ page }) => {
  await fresh(page)
  await page.click('text=Create lobby')
  await collapseTools(page)
  await page.click('.sidebar >> text=Directives')
  await page.locator('.proto', { hasText: 'Iron Directive' }).locator('button:has-text("Export")').click()
  const json = await page.inputValue('#proto-io')
  await page.click('.io button:has-text("Close")')
  await page.click('button:has-text("Import Directive")')
  await page.fill('#proto-io', json.replace('"Iron Directive"', '"Imported Iron"'))
  await page.click('.io button:has-text("Import")')
  await expect(page.locator('.proto', { hasText: 'Imported Iron' })).toContainText('7 changes from Standard Directive')
})
