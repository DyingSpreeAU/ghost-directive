// The app signed in to a simulated Bungie account: restore, resume, exact copies, moves.
import { test, expect, fresh, signIn, stubBungie, account, item, nameOf, I, B, HUNTER, TITAN, later, collapseTools, store, tools, editStore } from './helpers'

test('restore puts the run setup back: vaults extras, pulls run items home', async ({ page, baseURL }) => {
  const a = account()
  await stubBungie(page, a, baseURL!)
  await fresh(page)
  await signIn(page)
  await page.click('text=Create lobby')
  await page.waitForSelector('.equipped-grid .item')
  await collapseTools(page)
  await page.click('.seat.is-you .art-pick [role=radio][title^="Tablet of Ruin"]')
  await page.click('button:has-text("Begin run and lock route")')
  await page.waitForSelector('#arsenal')
  await later(page)
  await tools(page, () => page.click('.devtools button:has-text("All slots Legendary")'))
  await expect.poll(async () => (await store(page)).active.players[0].bungie?.restore?.equipped?.length ?? 0).toBe(8)
  // Normal play: Vault gun swapped in, a run helmet moved to the Titan, junk picked up.
  const h = a.chars[HUNTER]
  const k = h.eq.findIndex((x) => x.bucket === B.k); a.vault.push(h.eq.splice(k, 1, a.vault.shift()!)[0])
  const hm = h.eq.findIndex((x) => x.bucket === B.helm); a.chars[TITAN].inv.push(h.eq.splice(hm, 1)[0])
  h.inv.push(item(a, I.StayAway, B.e))
  a.location = false
  await page.click('#arsenal button:has-text("Restore my Guardian")')
  await page.click('.modal-foot button:has-text("Restore")')
  await expect(page.locator('.modal .restore-info')).toContainText('Run setup equipped.')
  expect(h.eq.map(nameOf)).toEqual(expect.arrayContaining(['Fatebringer', 'Helm']))
  expect(h.inv.map(nameOf)).not.toContain('StayAway')
})

