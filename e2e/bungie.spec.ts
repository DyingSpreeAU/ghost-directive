test('a duplicate copy is flagged, and can be swapped in as the run’s copy', async ({ page, baseURL }) => {
  const a = account()
  const p1 = item(a, I.Pariah, B.k), p2 = item(a, I.Pariah, B.k)
  a.chars[HUNTER].inv.push(p1, p2)
  await stubBungie(page, a, baseURL!)
  await fresh(page)
  await signIn(page)
  await page.click('text=Create lobby')
  await page.waitForSelector('.equipped-grid .item')
  await collapseTools(page)
  await page.click('.seat.is-you .art-pick [role=radio][title^="Tablet of Ruin"]')
  await page.click('button:has-text("Begin run and lock route")')
  await page.waitForSelector('#arsenal'); await later(page)
  await tools(page, () => page.click('.devtools button:has-text("All slots Legendary")'))
  await editStore(page, "s.active.players[0].inventory.push({ id: 'tu1', name: 'Pariah', slot: 'Kinetic', rarity: 'Legendary', source: 'trade-up', equipped: false })")
  await page.waitForSelector('#arsenal'); await later(page); await collapseTools(page)
  await page.click('#arsenal button:has-text("Sync drops now")')
  await expect.poll(async () => (await store(page)).active.players[0].inventory.find((i: { id: string }) => i.id === 'tu1')?.instanceId).toBe(p1.id)
  await expect(page.locator('.tile.is-outside')).toHaveCount(1)
  await page.locator('.tile.is-outside').click()
  await page.click('.tile-detail.is-outside button:has-text("This is the run")')
  await expect.poll(async () => (await store(page)).active.players[0].inventory.find((i: { id: string }) => i.id === 'tu1')?.instanceId).toBe(p2.id)
})

test('a trade-up pulls the Vault copy, not one already on the character', async ({ page, baseURL }) => {
  const a = account()
  const vaultCopy = item(a, I.Fatebringer, B.k); a.vault.push(vaultCopy)
  await stubBungie(page, a, baseURL!)
  await fresh(page)
  await signIn(page)
  await page.click('text=Create lobby')
  await page.waitForSelector('.equipped-grid .item')
  await collapseTools(page)
  await page.click('.seat.is-you .art-pick [role=radio][title^="Tablet of Ruin"]')
  await page.click('button:has-text("Begin run and lock route")')
  await page.waitForSelector('#arsenal'); await later(page)
  await tools(page, async () => { await page.click('.devtools button:has-text("All slots Legendary")'); await page.click('.devtools button:has-text("Empty inventory")') })
  await editStore(page, "for (let k = 0; k < 4; k++) s.active.players[0].inventory.push({ id: 'hj' + k, name: 'Hung Jury SR4', slot: 'Kinetic', rarity: 'Legendary', source: 'test', equipped: false })")
  await page.waitForSelector('#arsenal'); await later(page); await collapseTools(page)
  await page.locator('#arsenal .g-slot').first().locator('button:has-text("Trade up")').click()
  const inputs = page.locator('.modal .choice.trade-in:not([disabled])')
  for (let k = 0; k < 4; k++) await inputs.nth(k).click()
  await page.click('.modal-foot .btn-light')
  await expect(page.locator('.modal h2')).toContainText('Choose 1 of')
  await page.locator('.modal .choice-item', { hasText: 'Fatebringer' }).click()
  await page.click('.modal-foot .btn-light')
  await expect.poll(async () => (await store(page)).active.players[0].inventory.find((i: { name: string }) => i.name === 'Fatebringer')?.instanceId).toBe(vaultCopy.id)
  expect(a.chars[HUNTER].inv.map((x) => x.id)).toContain(vaultCopy.id)
})

